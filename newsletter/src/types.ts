export interface Env {
  ASSETS: Fetcher;
  APP_PASSWORD: string;
  SESSION_SECRET: string;
  ANTHROPIC_API_KEY: string;
  ECOMAIL_API_KEY?: string;
  SHOP_URL: string;
  SHOP_NAME: string;
  FROM_NAME: string;
  FROM_EMAIL: string;
  REPLY_TO: string;
  DEFAULT_LIST_ID: string;
}

export interface Product {
  id: string;
  name: string;
  url: string;
  image: string;
  price: number;
  /** Price before discount, when the product is on sale. */
  priceOriginal: number | null;
  discountPct: number | null;
  availability: string;
  inStock: boolean;
  flags: string[];
}

export interface EmailSection {
  title: string;
  text: string;
}

export interface EmailProductCopy {
  id: string;
  blurb: string;
  badge: string;
}

/** Copy generated by Claude and edited by the user. */
export interface EmailCopy {
  subject_variants: string[];
  preheader: string;
  headline: string;
  intro: string;
  hero_cta_text: string;
  hero_cta_url: string;
  sections: EmailSection[];
  products: EmailProductCopy[];
  closing: string;
  cta_text: string;
}

/** Everything the editor holds; sent back to the server for rendering / Ecomail. */
export interface EmailState {
  campaign: string;
  subject: string;
  copy: EmailCopy;
  products: Product[];
  heroImage: string;
}

export interface PlanTopic {
  id: string;
  name: string;
  sources: string[];
  angle: string;
  volume: number;
  keywords: string[];
  questions: string[];
  seasonality: { month: number; index: number }[];
  peak_months: number[];
}

export interface PlanSpecial {
  id: string;
  name: string;
  sources: string[];
  angle: string;
}

export interface Plan {
  source: string;
  topics: PlanTopic[];
  specials: PlanSpecial[];
}
