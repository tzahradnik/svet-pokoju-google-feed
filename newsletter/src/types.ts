export interface Env {
  ASSETS: Fetcher;
  APP_PASSWORD: string;
  /** Cloudflare Access: team domain (xyz.cloudflareaccess.com) and application AUD tag. When both are set, login is by one-time e-mail code only. */
  ACCESS_TEAM_DOMAIN?: string;
  ACCESS_AUD?: string;
  SESSION_SECRET: string;
  ANTHROPIC_API_KEY: string;
  ECOMAIL_API_KEY?: string;
  SHOP_URL: string;
  SHOP_NAME: string;
  FROM_NAME: string;
  FROM_EMAIL: string;
  REPLY_TO: string;
  DEFAULT_LIST_ID: string;
  /** Optional personal sign-off under the e-mail (name, role, square photo URL). */
  SIGNATURE_NAME?: string;
  SIGNATURE_ROLE?: string;
  SIGNATURE_PHOTO?: string;
  /** Published catalogue folder (GitHub Pages) – see tools/build_catalog.py */
  CATALOG_URL?: string;
}

export interface Product {
  id: string;
  name: string;
  url: string;
  image: string;
  price: number;
  /** Price before discount, when the product is on sale. */
  priceOriginal: number | null;
  discountPct: number | null;
  availability: string;
  inStock: boolean;
  flags: string[];
}

export interface EmailSection {
  title: string;
  text: string;
  /** Optional "read more" link to a blog article / guide on the shop. */
  link_url?: string;
  link_text?: string;
}

export interface EmailProductCopy {
  id: string;
  blurb: string;
  badge: string;
}

/** Copy generated by Claude and edited by the user. */
export interface EmailCopy {
  subject_variants: string[];
  preheader: string;
  headline: string;
  intro: string;
  hero_cta_text: string;
  hero_cta_url: string;
  sections: EmailSection[];
  products: EmailProductCopy[];
  closing: string;
  cta_text: string;
  /** Text the AI writes for the opening hook (mini story, lead-in line…); empty when the hook needs none. */
  hook?: string;
}

/** Opening element that grabs attention at the top of the e-mail. */
export type HookType = "none" | "personal" | "question" | "review" | "deadline" | "age" | "story" | "numbers";

export interface Hook {
  type: HookType;
  /** question: the real customer question and who asked (e.g. "Jana z Brna") */
  question?: string;
  asker?: string;
  /** review: real customer review, its author and star rating 1-5 */
  quote?: string;
  author?: string;
  rating?: number;
  /** deadline: what the deadline is for and the date text (e.g. "do 20. listopadu") */
  deadlineWhat?: string;
  deadline?: string;
  /** age: three buttons leading to categories */
  ages?: { label: string; url: string }[];
}

/** Everything the editor holds; sent back to the server for rendering / Ecomail. */
export interface EmailState {
  campaign: string;
  subject: string;
  copy: EmailCopy;
  products: Product[];
  heroImage: string;
  hook?: Hook;
  /** Greet by first name in the vocative (Ecomail *|VOKATIV|* with a fallback for contacts without a name). */
  greetByName?: boolean;
}

export interface PlanTopic {
  id: string;
  name: string;
  sources: string[];
  angle: string;
  volume: number;
  keywords: string[];
  questions: string[];
  seasonality: { month: number; index: number }[];
  peak_months: number[];
}

export interface PlanSpecial {
  id: string;
  name: string;
  sources: string[];
  angle: string;
}

export interface Plan {
  source: string;
  topics: PlanTopic[];
  specials: PlanSpecial[];
}
